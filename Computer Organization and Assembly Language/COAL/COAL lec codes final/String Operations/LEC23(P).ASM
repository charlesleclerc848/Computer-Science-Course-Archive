.MODEL SMALL
.STACK 100H
.DATA

STRING1 DB "EXAMPLE$"
LEN EQU $-STRING1
STRING2 DB LEN DUP("$")

.CODE
MAIN PROC 
    MOV AX,@DATA
    MOV DS,AX
    MOV ES,AX 
    
    MOV CX,LEN-1
    MOV SI,OFFSET STRING1 
    MOV DI,OFFSET STRING2
    
    REP MOVSB 
    
    MOV AH,09
    MOV DX,OFFSET STRING2
    INT 21H
    
    MOV AH,4CH 
    INT 21H
MAIN ENDP
END MAIN