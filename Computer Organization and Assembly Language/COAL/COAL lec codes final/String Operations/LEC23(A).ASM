.MODEL SMALL 
.STACK 100H
.DATA

STRING1 DB "HELLO$"
LEN EQU $-STRING1
STRING2 DB LEN DUP("$")
STRING3 DB LEN+3 DUP ("$")



.CODE
MAIN PROC 
    MOV AX,@DATA
    MOV DS,AX
    MOV ES,AX 
    
    MOV CX,LEN-1
    
    LEA SI,STRING1
    LEA DI,STRING2
    
    CLD
    REP MOVSB
    
    MOV CX,LEN+2
    LEA DI,STRING3
@LOOP:
    MOV AH,01
    
    INT 21H
    ; al --> ES:DI
  
    STOSB
    
    LOOP @LOOP
    
    MOV DX,OFFSET STRING3
    MOV AH,09
    INT 21H
    
    
    
    MOV AH,4CH
    INT 21H
MAIN ENDP
END MAIN
    
    
