.MODEL SMALL
.STACK 100H
.DATA

STRING2 DB "YASIN$"
LEN EQU $-STRING2 
NOTFOUND DB "NOT FOUND$"
FOUND DB "FOUND$"

.CODE
MAIN PROC 
    MOV AX,@DATA
    MOV DS,AX
    MOV ES,AX
    MOV CX,LEN-1
    
    MOV AL,"S" 
    MOV DI,OFFSET STRING2
    REPNZ SCASB 
    
    JNZ @DISPLAY
    
    MOV DX,OFFSET FOUND
    MOV AH,09
    INT 21H
    
    JMP EXIT
    
    
    @DISPLAY:
    MOV DX,OFFSET NOTFOUND 
    MOV AH,09
    INT 21H
    
    
EXIT:
    MOV AH,4CH
    INT 21H
MAIN ENDP
END MAIN