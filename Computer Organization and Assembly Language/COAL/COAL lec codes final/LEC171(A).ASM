.MODEL SMALL
.STACK 100H
.DATA



.CODE
MAIN PROC 
    MOV AX,@DATA
    MOV DS,AX  
    
    MOV AH,01
    INT 21H
    
    MOV BL,AL
    
    MOV CX,34EFH
    MOV DX,67ABH
    
    CALL CHARCTER_TO_BINARY
    ;AS SOON AS PROCEDURE IS CALLED, ADRESS OF NEXT INSTRUCTION IS MOVED TO STACK
    
    
    MOV AH,4CH 
    INT 21H
MAIN ENDP
;PROCEDURES ARE SAME AS FUNCTION IN HIGH LEVEL PROGRAMMING LANGUAGE
CHARCTER_TO_BINARY PROC
    ;INPUT , BL
    
    PUSH AX
    PUSH BX
    PUSH CX
    PUSH DX
    
      
    MOV CX,8
@LOOP:    
    SHL BL,1
    JC ONE
    MOV AH,02
    MOV DL,"0"
    INT 21H
    JMP ENDL
    ONE:
    MOV AH,02
    MOV DL,"1"
    INT 21H
    ENDL:
    LOOP @LOOP
    
    POP DX
    POP CX
    POP BX
    POP AX
    RET    
CHARCTER_TO_BINARY ENDP

END MAIN