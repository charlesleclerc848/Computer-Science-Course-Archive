.MODEL SMALL
.STACK 100H
.DATA
;alphab ABCDEFGHIJKLMNOPQRSTUVWXYZ
KEY DB "XQPOGHZBCADEIJUVFMNALRSTWY"  
NEWLINE DB 0DH,0AH,"$"
ENCRYPTED DB 50 DUP ("$")
.CODE
MAIN PROC
    MOV AX,@DATA
    MOV DS,AX
    
    MOV DI,OFFSET ENCRYPTED
    MOV BX,OFFSET KEY
    MOV AH,01
    
@LOOP:    
    INT 21H
    CMP AL,0DH
    JE @DISPLAY
    SUB AL,"A"
    
    XLAT
    MOV [DI],AL
    INC DI
    JMP @LOOP
@DISPLAY:    
    MOV DX,OFFSET ENCRYPTED
    MOV AH,09
    INT 21H
    MOV AH,4CH
    INT 21H
MAIN ENDP
END MAIN