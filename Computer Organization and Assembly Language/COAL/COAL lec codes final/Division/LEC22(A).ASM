 .MODEL SMALL
 .STACK 100H
 .DATA
 
 
 DIVISOR DW 10
 
 .CODE
 MAIN PROC 
    MOV AX,@DATA
    MOV DS,AX
    
    
    XOR CX,CX
    MOV AX,2345
    
    CALL OUTDEC
    
    XOR CX,CX
    MOV AX,7890  
    
    CALL OUTDEC
    
    MOV AH,4CH
    INT 21H
MAIN ENDP

OUTDEC PROC 
;INPUT: DIVIDEND MUST BE IN AX 
;INPUT: DIVISOR MUST BE IN MEMORY(DW)
;RETURN: NOTHING, ONLY PRINTING DECIMAL VALUES OF MUTIPLE DIGITS
PUSH AX
PUSH CX
PUSH DX
        
@LOOP:
    XOR DX,DX;XOR AH,AH
    DIV DIVISOR
    PUSH DX;PUSH AX
    INC CX
    CMP AL,0
    JNE @LOOP
    
@LOOP2:
    POP AX
    MOV DL,AL
    ADD DL,"0"
    MOV AH,02
    INT 21H
    
    LOOP @LOOP2
POP DX
POP CX
POP AX

RET    
OUTDEC ENDP
 END MAIN