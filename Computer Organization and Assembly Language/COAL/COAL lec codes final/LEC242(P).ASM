.MODEL SMALL
.STACK 100H
.DATA


STRING1 DB "SECTION P$"
LEN EQU $-STRING1 
STRING2 DB "CHARACTER FOUND$"
STRING3 DB "CHARACTER NOT FOUND $"

.CODE 
MAIN PROC 
    MOV AX,@DATA
    MOV DS,AX
    MOV ES,AX 
    
    MOV AL,"Z"
    LEA DI,STRING1 
    MOV CX,LEN-1
    
    REPNZ SCASB 
    
    JNZ @DISPLAY
    
    MOV DX,OFFSET STRING2
    MOV AH,09
    INT 21H 
    JMP EXIT
    
    @DISPLAY:
    MOV DX,OFFSET STRING3
    MOV AH,09
    INT 21H
EXIT:    
MOV AH,4CH
INT 21H

MAIN ENDP
END MAIN
    