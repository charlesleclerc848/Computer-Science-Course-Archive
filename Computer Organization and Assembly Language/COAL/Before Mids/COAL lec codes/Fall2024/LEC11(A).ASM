.MODEL SMALL
.STACK 100H
.DATA
          
STRING DB "INPUT SEQUENCE OF CHARACTERS TERMINATED BY SPACE $"
NEWLINE DB 0AH,0DH,"$"
.CODE
MAIN PROC
    MOV AX,@DATA
    MOV DS,AX
    
    MOV AH,09
    MOV DX, OFFSET STRING 
    INT 21H
    
    ;NEWLINE 
    MOV AH,02
    MOV DL,0AH
    INT 21H
    
    MOV AH,02
    MOV DL,0DH
    INT 21H
    
    ;ADD ANOTHER NEWLINE
    MOV DX,OFFSET NEWLINE
    MOV AH,09
    INT 21H
    
    INPUT:
    MOV AH,01H
    INT 21H
    
    SUB AL," ";20H
    JZ EXIT
    JMP INPUT
    
    
    
    EXIT:
    MOV AH,4CH
    INT 21H
MAIN ENDP
END MAIN