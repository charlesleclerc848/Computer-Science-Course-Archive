.MODEL SMALL
.STACK 100H
.DATA

NEWLINE DB 0AH,0DH,"$"
STRING DB "ENTER SEQUENE OF CHARACTERS TERMINATED BY SPACE$"

.CODE
MAIN PROC
    MOV AX,@DATA
    MOV DS,AX
    
    MOV AH,09
    MOV DX,OFFSET STRING
    INT 21H 
    
    MOV AH,09
    MOV DX,OFFSET NEWLINE
    INT 21H
    
    @LOOP:
    MOV AH,01
    INT 21H
    XOR AL," "
    JZ EXIT
    JMP @LOOP
    
    EXIT:
    MOV AH,4CH
    INT 21H
    
MAIN ENDP
END MAIN